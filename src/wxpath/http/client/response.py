from dataclasses import dataclass, field
from typing import Optional

from wxpath.http.client.request import Request


@dataclass
class Response:
    """Crawler response, including streamed browser page completion state.

    generated by AI - requires human review
    """

    request: Request
    status: int
    body: bytes | str
    headers: dict[str, str] | None = None
    error: Optional[Exception] = field(default=None, kw_only=True)

    request_start: float | None = None
    response_end: float | None = None
    page_url: str | None = None
    complete: bool = True
    terminal: bool = False

    @property
    def latency(self) -> float:
        return self.response_end - self.request_start
