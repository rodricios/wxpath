import time
from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class Pagination:
    """Browser pagination instructions for one crawl request.

    Args:
        click_xpath: XPath for the next-page control.
        max_pages: Page cap including the initial page.

    generated by AI - requires human review
    """

    click_xpath: str
    max_pages: int = 100

    def __post_init__(self) -> None:
        if not self.click_xpath.strip():
            raise ValueError('pagination click XPath must not be empty')
        if self.max_pages < 1:
            raise ValueError('pagination max_pages must be at least 1')


@dataclass
class Request:
    """HTTP request envelope used by the crawler."""

    url: str
    method: str = 'GET'
    headers: dict[str, str] = field(default_factory=dict)
    timeout: float | None = None

    retries: int = 0
    max_retries: int | None = None
    dont_retry: bool = False

    meta: dict[str, Any] = field(default_factory=dict)
    pagination: Pagination | None = None

    created_at: float = field(default_factory=time.monotonic)

    def copy_for_retry(self) -> 'Request':
        """Create a copy incrementing the retry counter for scheduling."""
        return Request(
            url=self.url,
            method=self.method,
            headers=self.headers,
            timeout=self.timeout,
            retries=self.retries + 1,
            max_retries=self.max_retries,
            dont_retry=self.dont_retry,
            meta=self.meta,
            pagination=self.pagination,
        )

    @property
    def hostname(self) -> str:
        from urllib.parse import urlsplit

        return urlsplit(self.url).hostname or ''
